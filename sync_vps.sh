#!/usr/bin/env bash
# ==============================================================================
# sync_vps.sh — Обновление Space на VPS из Git и перезапуск сервиса Машеньки
# ==============================================================================
set -euo pipefail

echo "📥 Подтягиваем свежие изменения из Git..."
cd /home/work/Space
git pull origin main

echo "🔄 Перезапуск сервиса Машеньки..."
systemctl restart masha.service
echo "✅ Готово! Машенька обновлена из репозитория Space."
