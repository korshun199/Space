#!/usr/bin/env bash
# ==============================================================================
# sync.sh — Команда «СИНХРОНИЗИРУЙ»: Git commit & push с ноутбука -> Git pull на VPS
# ==============================================================================
set -euo pipefail

COMMIT_MSG="${1:-Синхронизация Space (ноутбук -> GitHub -> VPS)}"
CURRENT_BRANCH=$(git branch --show-current)

echo "=========================================================="
echo "🚀 1. Фиксация изменений на ноутбуке (ветка: $CURRENT_BRANCH)..."
echo "=========================================================="
git add -A
if git diff --cached --quiet; then
    echo "ℹ️ Нет новых изменений для коммита на ноутбуке."
else
    git commit -m "$COMMIT_MSG"
fi

echo "=========================================================="
echo "⬆️ 2. Отправка в GitHub (origin $CURRENT_BRANCH)..."
echo "=========================================================="
git push origin "$CURRENT_BRANCH"

echo "=========================================================="
echo "📥 3. Подтягивание изменений на боевом VPS..."
echo "=========================================================="
ssh -o ConnectTimeout=8 46.8.221.179 "cd /home/work/Space && git fetch && git checkout $CURRENT_BRANCH && git pull origin $CURRENT_BRANCH"

echo "=========================================================="
echo "✅ СИНХРОНИЗАЦИЯ УСПЕШНО ЗАВЕРШЕНА!"
echo "   Ветка: $CURRENT_BRANCH"
echo "   VPS: /home/work/Space обновлён до актуального состояния."
echo "=========================================================="
